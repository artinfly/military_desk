"""Редактируемый текст справки: только текст и известные поля карточки."""

from django.conf import settings
from django.db import models

DEFAULT_TITLE = (
    "Справка на отсрочку от призыва на военную службу "
    "по мобилизации и в военное время"
)
DEFAULT_ORGANIZATION = (
    "АО «Научно-производственная корпорация «Уралвагонзавод» " "им. Ф.Э. Дзержинского»"
)
DEFAULT_BODY = """Гражданин {{ФИО}}, {{ГодРождения}} года рождения, пребывающий в запасе и работающий в {{Организация}} в должности (по профессии) {{Должность}}, воинское звание {{Звание}}, состав (профиль) {{Состав}}, № ВУС {{ВУС}}, документ воинского учёта: серия {{Серия}} №{{Номер}} имеет отсрочку от призыва на военную службу по мобилизации и в военное время на основании (нужное подчеркнуть) пп. «б», «в» п. 2 «Правил бронирования на период мобилизации и на военное время граждан Российской Федерации, пребывающих в запасе Вооружённых Сил РФ, федеральных органах государственной власти, органах местного самоуправления и организациях», утверждённых постановлением Правительства Российской Федерации от 05 июля 2024 года № 766.
Приказ «О бронировании» от __________ №{{ПриказНомер}}

Руководитель организации	ФИО
М.П.

«_____» ______________ 202___ г."""


class CertificateTemplate(models.Model):
    name = models.CharField("Название шаблона", max_length=150, default=DEFAULT_TITLE)
    organization = models.CharField(
        "Организация", max_length=255, blank=True, default=DEFAULT_ORGANIZATION
    )
    body = models.TextField("Текст справки", default=DEFAULT_BODY)
    updated_at = models.DateTimeField("Изменён", auto_now=True)
    updated_by = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.SET_NULL,
        null=True,
        editable=False,
    )

    class Meta:
        verbose_name = "шаблон справки"
        verbose_name_plural = "шаблоны справок"

    def __str__(self):
        return self.name
